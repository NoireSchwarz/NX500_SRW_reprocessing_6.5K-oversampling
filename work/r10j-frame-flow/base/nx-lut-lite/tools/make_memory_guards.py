#!/usr/bin/env python3
"""Generate exact read-only app metadata guards from official NX500 1.12 ELF."""
import argparse
import hashlib
from pathlib import Path
import struct
from elftools.elf.elffile import ELFFile
p=argparse.ArgumentParser(description=__doc__);p.add_argument('app',type=Path);a=p.parse_args()
b=a.app.read_bytes();assert hashlib.sha256(b).hexdigest()=='55dcc78143724435a2e38b9e0d809960bd728668634bbcf7532ce137f882eb04'
fnv=2166136261
for v in b:fnv=((fnv^v)*16777619)&0xffffffff
lines=['/* Generated by tools/make_memory_guards.py; exact official NX500 1.12 app. */','#ifndef NXL_MEMORY_GUARDS_H','#define NXL_MEMORY_GUARDS_H',f'#define MEM_APP_BYTES {len(b)}u',f'#define MEM_APP_FNV 0x{fnv:08x}u','struct mem_guard {unsigned address,words[8];};','static const struct mem_guard mem_guards[]={']
with a.app.open('rb') as f:
 e=ELFFile(f)
 for addr in (0x1d1ca8,0x1d1da0,0x1eab10,0x1eac7c):
  s=next(s for s in e.iter_segments() if s['p_type']=='PT_LOAD' and s['p_vaddr']<=addr<s['p_vaddr']+s['p_filesz'])
  words=struct.unpack('<8I',s.data()[addr-s['p_vaddr']:addr-s['p_vaddr']+32])
  lines.append('{0x%xu,{%s}},'%(addr,','.join('0x%08xu'%v for v in words)))
lines+=['};','#define MEM_GUARD_COUNT (sizeof mem_guards/sizeof mem_guards[0])','#endif']
(Path(__file__).resolve().parents[1]/'src/memory_guards.h').write_text('\n'.join(lines)+'\n')
print('Generated four app code guards; app FNV32',hex(fnv))

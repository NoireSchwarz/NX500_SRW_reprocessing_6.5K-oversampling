#!/usr/bin/env python3
"""Generate compact UI tables from editable metadata and bitmap glyph sources."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
profiles=json.loads((ROOT/'data/looks-info.json').read_text())
extra=[{'id':'','name':'还原 LUT','tone':'关闭当前 LUT，恢复本次会话备份。','scene':'只还原色彩处理，模组仍保留。'},
 {'id':'?','name':'自定义滤镜','tone':'自定义 LUT，暂无专属简介。','scene':'按 OK 应用，MENU 返回。'},
 {'id':'@video','name':'视频 LUT','tone':'使用当前已应用的 LUT 与强度。','scene':'换表前关闭视频，完成后再开启。'}]
for row in extra:row['group']='other'
def quote(s):return json.dumps(s,ensure_ascii=False)
lines=['/* Generated by tools/make_ui_assets.py. AGPL-3.0-only */',
 '#ifndef NXL_LOOK_INFO_H','#define NXL_LOOK_INFO_H',
 '#define NXL_LOOK_INFO_VERSION "0.3.4-native-allocation"',
 'struct nxl_look_info { const char *id,*name,*tone,*scene,*group; };']
for label,row in zip(('nxl_restore_info','nxl_unknown_info','nxl_video_info'),extra):
 lines.append('static const struct nxl_look_info '+label+'={'+','.join(quote(row[k]) for k in ('id','name','tone','scene','group'))+'};')
lines.append('static const struct nxl_look_info nxl_look_infos[]={')
for row in profiles:lines.append('{'+','.join(quote(row[k]) for k in ('id','name','tone','scene','group'))+'},')
lines+=['};','#endif'];(ROOT/'src/look_info.h').write_text('\n'.join(lines)+'\n')
glyphs=json.loads((ROOT/'data/ui-glyphs.json').read_text())
needed=set(chr(c) for c in range(32,127))
needed.update(c for file in ('menu.c','browser.h') for c in (ROOT/'src'/file).read_text() if ord(c)>=128)
for row in profiles+extra:
 for value in row.values():needed.update(value)
missing=[c for c in needed if ord(c)>=32 and str(ord(c)) not in glyphs]
if missing:raise ValueError('Missing glyphs: '+''.join(sorted(missing)))
lines=['/* Noto Sans CJK SC bitmap subset; SIL OFL in vendor/NotoSans-OFL.txt. */',
 '#ifndef NXL_UI_FONT_H','#define NXL_UI_FONT_H',
 'struct nxl_ui_glyph { unsigned cp,advance; unsigned row[28]; };',
 'static const struct nxl_ui_glyph nxl_ui_font[]={']
for cp,g in sorted(glyphs.items(),key=lambda x:int(x[0])):
 lines.append('{'+cp+','+str(g['advance'])+',{'+','.join(hex(v) for v in g['rows'])+'}},')
lines+=['};','static const struct nxl_ui_glyph *nxl_ui_glyph(unsigned cp) {',
 'unsigned lo=0,hi=sizeof nxl_ui_font/sizeof nxl_ui_font[0];',
 'while(lo<hi){unsigned mid=(lo+hi)/2;if(nxl_ui_font[mid].cp<cp)lo=mid+1;else hi=mid;}',
 'if(lo<sizeof nxl_ui_font/sizeof nxl_ui_font[0] && nxl_ui_font[lo].cp==cp)return &nxl_ui_font[lo];',
 'return nxl_ui_glyph(63);','}','#endif']
(ROOT/'src/ui_font.h').write_text('\n'.join(lines)+'\n')
print('Generated',len(glyphs),'glyphs and',len(profiles),'filter descriptions')
